/**
 * 원장(ledger) 샘플 — <b>동시성 있는 수량 갱신</b>의 참조 구현.
 *
 * <p>"잔액을 읽어서 검증하고 차감한 뒤 이력을 남긴다"는 형태는 도메인만 바뀔 뿐 어디에나 나온다 —
 * 재고 차감, 포인트 사용, 쿠폰 소진, 좌석 예약, 한도 관리. 이 패키지는 그 형태를 계좌 이체로 구현해
 * 다음 네 가지를 보여준다.
 *
 * <ol>
 *   <li><b>단일 트랜잭션</b> — 출금·입금·이력적재가 전부 성공하거나 전부 롤백된다.</li>
 *   <li><b>잠금 순서 고정</b> — 두 행을 키의 사전순으로 잠근다. A→B 와 B→A 가 동시에 들어와도
 *       교착(deadlock)이 생기지 않는다.</li>
 *   <li><b>DB 측 산술 갱신</b> — {@code balance = balance + ?} 로 갱신해 읽기-수정-쓰기 사이의
 *       갱신 손실(lost update)을 없앤다.</li>
 *   <li><b>다중 방어선</b> — 애플리케이션 검증 + DB CHECK 제약. 어느 한쪽이 뚫려도 음수 잔액은 안 생긴다.</li>
 * </ol>
 *
 * <p>패턴만 가져가고 이 패키지는 지운다. 삭제 대상 목록은 {@code com.example.demo.sample} 참고.
 */
